"""Pure functions turning subscriber state into router configuration.

Nothing in here touches the system, which keeps it easy to test and to
inspect (`eyesp show nft`, `eyesp show tc`, ...).
"""

from __future__ import annotations

import math
from dataclasses import dataclass

from .config import Config
from .db import Plan, Subscriber

TABLE = "eyesp"
DEFAULT_CLASS = 0xFFFF


def dnsmasq_conf(cfg: Config, static_hosts: dict[str, str] | None = None) -> str:
    """Main dnsmasq config: DHCP for provisioned subscribers + a caching resolver."""
    net = cfg.access_net
    lines = [
        "# Generated by eyesp. DHCP + DNS for subscribers.",
        f"interface={cfg.access_if}",
        "bind-interfaces",
        "user=root",
        "no-hosts",
        f"domain={cfg.domain}",
        f"local=/{cfg.domain}/",
        # Only hand out leases to MACs listed in the hosts file (no rogue CPEs).
        f"dhcp-range={net.network_address},static,{net.netmask},12h",
        f"dhcp-option=option:router,{cfg.gateway}",
        f"dhcp-option=option:dns-server,{cfg.gateway}",
        f"dhcp-hostsfile={cfg.dhcp_hosts_path}",
        f"dhcp-leasefile={cfg.state_dir / 'dnsmasq.leases'}",
        "dhcp-authoritative",
        f"pid-file={cfg.dnsmasq_pid}",
        f"log-facility={cfg.state_dir / 'dnsmasq.log'}",
        "log-dhcp",
    ]
    if static_hosts is None:
        lines.append("server=1.1.1.1")
        lines.append("server=9.9.9.9")
    else:
        # Lab mode: there is no real internet, so answer for a few names ourselves.
        lines.append("no-resolv")
        for name, ip in sorted(static_hosts.items()):
            lines.append(f"address=/{name}/{ip}")
    return "\n".join(lines) + "\n"


def dhcp_hosts(subs: list[Subscriber]) -> str:
    """dnsmasq dhcp-hostsfile: one static lease per subscriber."""
    return "".join(f"{s.mac},{s.ip},{s.name}\n" for s in subs)


def nft_ruleset(cfg: Config, subs: list[Subscriber]) -> str:
    """Firewall, NAT, per-subscriber traffic classes and byte counters.

    The ruleset deletes and recreates its own table in one atomic transaction,
    so applying it is idempotent and never leaves the router half-configured.
    """
    wan, acc, net = cfg.wan_if, cfg.access_if, cfg.access_net
    suspended = [s.ip for s in subs if s.status == "suspended"]

    out = [f"table ip {TABLE}", f"delete table ip {TABLE}", f"table ip {TABLE} {{"]
    for s in subs:
        out.append(f'  counter sub{s.id}_up {{ comment "{s.name}" }}')
        out.append(f'  counter sub{s.id}_down {{ comment "{s.name}" }}')
    out.append("")
    out.append("  set suspended {")
    out.append("    type ipv4_addr")
    if suspended:
        out.append(f"    elements = {{ {', '.join(suspended)} }}")
    out.append("  }")
    out.append("")
    out += [
        "  chain input {",
        "    type filter hook input priority filter; policy drop;",
        "    iif lo accept",
        "    ct state established,related accept",
        "    meta l4proto icmp accept",
        f'    iifname "{acc}" udp dport {{ 53, 67 }} accept',
        f'    iifname "{acc}" tcp dport 53 accept',
        "  }",
        "",
        "  chain forward {",
        "    type filter hook forward priority filter; policy drop;",
        "    ip saddr @suspended drop",
        "    ip daddr @suspended drop",
    ]
    for s in subs:
        # Upload: only accept the subscriber's IP from the subscriber's MAC (anti-spoofing).
        out.append(
            f'    iifname "{acc}" oifname "{wan}" ether saddr {s.mac} ip saddr {s.ip} '
            f'meta priority set 1:{s.id:x} counter name "sub{s.id}_up" accept'
        )
        # Download: return traffic only (subscribers sit behind NAT anyway).
        out.append(
            f'    iifname "{wan}" oifname "{acc}" ip daddr {s.ip} ct state established,related '
            f'meta priority set 1:{s.id:x} counter name "sub{s.id}_down" accept'
        )
    out += [
        "  }",
        "",
        "  chain postrouting {",
        "    type nat hook postrouting priority srcnat; policy accept;",
        f'    oifname "{wan}" ip saddr {net} masquerade',
        "  }",
        "}",
    ]
    return "\n".join(out) + "\n"


def _shaper(dev: str, rates: list[tuple[int, int]], leaf: str | None) -> list[str]:
    """HTB root with one class per subscriber.

    No tc filters are needed: nftables sets skb->priority to the subscriber's
    class id (1:<id>) and HTB classifies on that directly.

    `leaf` is the per-class queue (fq_codel keeps latency low under load);
    None falls back to the kernel default (pfifo).
    """
    def leaf_cmd(cid: str) -> list[str]:
        return [f"qdisc add dev {dev} parent 1:{cid} {leaf}"] if leaf else []

    cmds = [
        f"qdisc del dev {dev} root",
        f"qdisc add dev {dev} root handle 1: htb default {DEFAULT_CLASS:x}",
        f"class add dev {dev} parent 1: classid 1:{DEFAULT_CLASS:x} htb rate 10gbit quantum 60000",
        *leaf_cmd(f"{DEFAULT_CLASS:x}"),
    ]
    for sub_id, mbps in rates:
        cid = f"{sub_id:x}"
        cmds += [
            f"class add dev {dev} parent 1: classid 1:{cid} htb rate {mbps}mbit ceil {mbps}mbit",
            *leaf_cmd(cid),
        ]
    return cmds


def tc_batch(cfg: Config, subs: list[Subscriber], plans: dict[str, Plan],
             leaf: str | None = "fq_codel") -> str:
    """Traffic shaping: upload shaped leaving the WAN, download leaving the access side."""
    up = [(s.id, plans[s.plan].up_mbps) for s in subs]
    down = [(s.id, plans[s.plan].down_mbps) for s in subs]
    return "\n".join(_shaper(cfg.wan_if, up, leaf) + _shaper(cfg.access_if, down, leaf)) + "\n"


@dataclass
class InvoiceLine:
    sub: Subscriber
    plan: Plan
    used_bytes: int
    overage_gb: int
    amount_cents: int


def invoice(sub: Subscriber, plan: Plan, up: int, down: int) -> InvoiceLine:
    used = up + down
    over = 0
    if plan.cap_gb is not None:
        over = max(0, math.ceil(used / 1e9 - plan.cap_gb))
    return InvoiceLine(sub, plan, used, over, plan.price_cents + over * plan.overage_cents_per_gb)
